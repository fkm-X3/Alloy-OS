/*
 * Alloy OS Desktop Environment — native userland DE
 *
 * Connects to the in-kernel Wayland server, creates surfaces,
 * and draws the desktop, panel, and app launcher directly.
 * Uses native Alloy OS Wayland protocol + SHM syscalls.
 *
 * Matches the visual design of de/ (Qt6 QML prototype).
 */

#include "wayland_client.h"
#include "stdio.h"
#include "alloy_syscall.h"
#include "stdlib.h"

#define NULL ((void*)0)

typedef __SIZE_TYPE__ size_t;

/* ───── Alloy-specific SHM syscalls ───── */

static int alloy_shm_alloc(unsigned int width, unsigned int height,
                           unsigned int bpp) {
    return syscall(SYS_ALLOC_SHM, (int)width, (int)height, (int)bpp, 0, 0);
}

static void *alloy_shm_user_vaddr(int fd) {
    return (void*)syscall(SYS_SHM_USER_VADDR, fd, 0, 0, 0, 0);
}

/* ───── Memory helpers ───── */

static void mymemcpy(void *dst, const void *src, size_t n) {
    unsigned char *d = (unsigned char *)dst;
    const unsigned char *s = (const unsigned char *)src;
    for (size_t i = 0; i < n; ++i) d[i] = s[i];
}

static void mymemset(void *s, int c, size_t n) {
    unsigned char *p = (unsigned char *)s;
    for (size_t i = 0; i < n; ++i) p[i] = (unsigned char)c;
}

static int strequal(const char *a, const char *b) {
    while (*a && *b) {
        if (*a != *b) return 0;
        ++a; ++b;
    }
    return *a == *b;
}

/* ───── Font and drawing (basic 8x8 bitmap font) ───── */

struct wl_display *g_display = NULL;

#define SCREEN_W 1024
#define SCREEN_H 768

static void put_pixel(unsigned int *fb, int x, int y, unsigned int color) {
    if (x < 0 || x >= SCREEN_W || y < 0 || y >= SCREEN_H) return;
    fb[y * SCREEN_W + x] = color;
}

static void fill_rect(unsigned int *fb, int x, int y, int w, int h,
                      unsigned int c) {
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x >= SCREEN_W || y >= SCREEN_H) return;
    if (x + w > SCREEN_W) w = SCREEN_W - x;
    if (y + h > SCREEN_H) h = SCREEN_H - y;
    for (int row = 0; row < h; ++row)
        for (int col = 0; col < w; ++col)
            fb[(y + row) * SCREEN_W + x + col] = c;
}

