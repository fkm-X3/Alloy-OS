void draw_char(unsigned int *fb, int x, int y, unsigned char c,
               unsigned int fg, unsigned int bg) {
    if (c >= 128) return;
    for (int row = 0; row < 8; ++row) {
        unsigned char line = font[c][row];
        for (int col = 0; col < 8; ++col) {
            unsigned int val = (line & (1 << (7 - col))) ? fg : bg;
            put_pixel(fb, x + col, y + row, val);
        }
    }
}

void draw_str(unsigned int *fb, int x, int y, const char *s,
              unsigned int fg, unsigned int bg) {
    int cx = x;
    while (*s) {
        if (*s == '\n') { cx = x; y += 10; }
        else { draw_char(fb, cx, y, *s, fg, bg); cx += 8; }
        ++s;
    }
}
