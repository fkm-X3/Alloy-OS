/// 8x16 bitmap font renderer
#[derive(Debug, Clone)]
pub struct BitmapFont8x16;

impl BitmapFont8x16 {
    pub fn new() -> Self {
        Self
    }

    fn glyph_data(ch: char) -> Option<&'static [u8]> {
        let code = ch as u32;
        if !(32..=126).contains(&code) {
            return None;
        }
        let offset = ((code - 32) as usize) * 16;
        Some(&FONT_8X16[offset..offset + 16])
    }
}

impl Font for BitmapFont8x16 {
    fn glyph_metrics(&self, _ch: char) -> Option<GlyphMetrics> {
        Some(GlyphMetrics {
            width: 8,
            height: 16,
            advance_x: 8,
            bearing_x: 0,
            bearing_y: 0,
        })
    }

    fn render_glyph(
        &self,
        ch: char,
        pixels: &mut [u32],
        buf_width: u32,
        buf_height: u32,
        x: u32,
        y: u32,
        color: u32,
        bg_color: u32,
    ) {
        let Some(glyph) = Self::glyph_data(ch) else {
            return;
        };

        for row in 0..16u32 {
            let abs_y = y + row;
            if abs_y >= buf_height {
                break;
            }
            let byte = glyph[row as usize];
            for col in 0..8u32 {
                let abs_x = x + col;
                if abs_x >= buf_width {
                    break;
                }
                let idx = (abs_y * buf_width + abs_x) as usize;
                if idx >= pixels.len() {
                    continue;
                }
                pixels[idx] = if (byte & (0x80 >> col)) != 0 { color } else { bg_color };
            }
        }
    }

    fn char_width(&self) -> u32 { 8 }
    fn char_height(&self) -> u32 { 16 }
    fn line_height(&self) -> u32 { 18 }
}

impl Default for BitmapFont8x16 {
    fn default() -> Self { Self::new() }
}
