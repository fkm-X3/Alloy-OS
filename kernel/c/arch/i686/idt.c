extern void rust_handle_page_fault(uint32_t addr, uint32_t err_code);

void exception_handler(struct interrupt_frame* frame) {
    uint32_t int_no = frame->int_no;
    uint32_t err_code = frame->err_code;

    if (int_no == 14) {
        uint32_t fault_addr = 0;
        asm volatile ("mov %%cr2, %0" : "=r"(fault_addr));

        serial_print("\n!!! PAGE FAULT at 0x");
        serial_print_hex(fault_addr);
        serial_print(" Error Code: ");
        serial_print_hex(err_code);
        serial_print("\n");

        if (err_code & 0x4) {
            serial_print("User-mode page fault, terminating current task...\n");
            rust_handle_page_fault(fault_addr, err_code);
            return;
        }
    }

    serial_print("\n!!! EXCEPTION: ");
    if (int_no < 19) {
        serial_print(exception_messages[int_no]);
    } else {
        serial_print("Unknown Exception");
    }
    serial_print(" (");
    serial_print_hex(int_no);
    serial_print(")\n");
    serial_print("Error Code: ");
    serial_print_hex(err_code);
    serial_print("\n");

    serial_print("System halted.\n");
    while(1) {
        asm volatile("cli; hlt");
    }
}

extern void keyboard_handler();
extern void mouse_handler();
extern void timer_handler();

void irq_handler(struct interrupt_frame* frame) {
    uint32_t irq_no = frame->int_no;

    switch (irq_no) {
        case 0:
            timer_handler();
            break;
        case 1:
            keyboard_handler();
            break;
        case 12:
            mouse_handler();
            break;
        default:
            break;
    }

    if (irq_no >= 8) {
        outb(PIC2_COMMAND, 0x20);
    }
    outb(PIC1_COMMAND, 0x20);
}

