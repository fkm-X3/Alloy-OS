pub const ALLOY_MONO: BitmapFont = BitmapFont {
    glyph_width: 8,
    glyph_height: 16,
    first_char: 0x20,
    last_char: 0x7E,
    data: ALLOY_MONO_8X16_DATA,
};

pub fn measure_text(font: &BitmapFont, text: &str) -> u32 {
    text.len() as u32 * font.glyph_width
}

pub fn draw_text(
    pixels: &mut [u32],
    stride: u32,
    font: &BitmapFont,
    text: &str,
    x: i32,
    y: i32,
    fg_color: u32,
    bg_color: Option<u32>,
) -> i32 {
    if stride == 0 {
        return 0;
    }

    let mut cursor_x = x;
    let glyph_bytes = ((font.glyph_width * font.glyph_height) / 8) as usize;

    for ch in text.bytes() {
        if ch < font.first_char || ch > font.last_char {
            cursor_x += font.glyph_width as i32;
            continue;
        }

        let glyph_index = (ch - font.first_char) as usize;
        let glyph_offset = glyph_index * glyph_bytes;
        let glyph_data = &font.data[glyph_offset..glyph_offset + glyph_bytes];

        let mut bit_index = 0;
        for gy in 0..font.glyph_height {
            for gx in 0..font.glyph_width {
                let byte_idx = bit_index / 8;
                let bit_idx = 7 - (bit_index % 8);
                let pixel_on = (glyph_data[byte_idx] >> bit_idx) & 1 == 1;

                let px = cursor_x + gx as i32;
                let py = y + gy as i32;

                if px >= 0 && py >= 0 && (px as u32) < stride && (py as u32) < (pixels.len() as u32 / stride) {
                    let offset = ((py as u32 * stride) + px as u32) as usize;
                    if pixel_on {
                        pixels[offset] = fg_color;
                    } else if let Some(bg) = bg_color {
                        pixels[offset] = bg;
                    }
                }

                bit_index += 1;
            }
        }

        cursor_x += font.glyph_width as i32;
    }

    cursor_x
}

pub fn draw_text_centered(
    pixels: &mut [u32],
    stride: u32,
    font: &BitmapFont,
    text: &str,
    y: i32,
    available_width: u32,
    fg_color: u32,
) -> i32 {
    let text_width = measure_text(font, text);
    let x = ((available_width.saturating_sub(text_width)) / 2) as i32;
    draw_text(pixels, stride, font, text, x, y, fg_color, None)
}
